"""`sf build`: skills/ (source) -> plugins/ + .claude-plugin/marketplace.json (generated).

Output is deterministic so `sf build --check` can diff a fresh build against the committed tree.
"""

from __future__ import annotations

import filecmp
import json
import shutil
import tempfile
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from skill_factory import yamlio
from skill_factory.models.market import Market
from skill_factory.spec import SkillDir, SkillError, discover, load_skill, spec_sha256

# Authoring-only files that never ship inside a plugin.
EXCLUDE = {"spec.yaml", "evals", "fixtures", "__pycache__", ".DS_Store"}
GENERATED_NOTE = "Generated by `sf build` from skills/ and market.yaml. Do not edit by hand."
HASH_MARKER = "sf:spec-sha256="


class BuildError(Exception):
    def __init__(self, problems: list[str]) -> None:
        self.problems = problems
        super().__init__("; ".join(problems))


@dataclass
class BuildResult:
    plugins: dict[str, list[str]] = field(default_factory=dict)  # plugin -> skill names
    warnings: list[str] = field(default_factory=list)


def load_market(root: Path) -> Market:
    path = root / "market.yaml"
    if not path.is_file():
        raise BuildError(["missing market.yaml"])
    try:
        return Market.model_validate(yamlio.load(path))
    except ValidationError as e:
        raise BuildError([f"market.yaml: {err['loc']}: {err['msg']}" for err in e.errors()]) from e


def load_all(root: Path) -> list[SkillDir]:
    skills: list[SkillDir] = []
    problems: list[str] = []
    for path in discover(root):
        try:
            skills.append(load_skill(path))
        except SkillError as e:
            problems.extend(f"{e.skill}: {p}" for p in e.problems)
    if problems:
        raise BuildError(problems)
    return skills


def _write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def _copy_skill(skill: SkillDir, dest: Path) -> None:
    shutil.copytree(skill.path, dest, ignore=lambda _d, names: [n for n in names if n in EXCLUDE])
    md = dest / "SKILL.md"
    text = md.read_text().rstrip("\n")
    marker = f"<!-- {HASH_MARKER}{spec_sha256(skill.spec_path)} sf:version={skill.spec.version} -->"
    md.write_text(f"{text}\n\n{marker}\n")


def _plugin_readme(name: str, description: str, repo: str, skills: list[SkillDir]) -> str:
    rows = "\n".join(f"| `{s.name}` | {s.spec.version} | {s.spec.goal.strip()} |" for s in skills)
    return (
        f"# {name}\n\n{description}\n\n<!-- {GENERATED_NOTE} -->\n\n"
        f"## Install\n\n```\n/plugin install {name} --marketplace {repo}\n```\n\n"
        f"## Skills\n\n| Skill | Version | Goal |\n|---|---|---|\n{rows}\n"
    )


def _render(root: Path, out: Path) -> BuildResult:
    """Render plugins/ and .claude-plugin/ under `out`."""
    market = load_market(root)
    skills = load_all(root)
    result = BuildResult()

    by_plugin: dict[str, list[SkillDir]] = defaultdict(list)
    for s in skills:
        by_plugin[s.spec.plugin_name].append(s)

    missing = sorted(set(by_plugin) - set(market.plugins))
    if missing:
        raise BuildError(
            [f"plugin {p!r} is used by a skill but not declared in market.yaml" for p in missing]
        )

    entries = []
    for pname in sorted(market.plugins):
        pdef = market.plugins[pname]
        members = sorted(by_plugin.get(pname, []), key=lambda s: s.name)
        if not members:
            result.warnings.append(f"plugin {pname!r} has no skills; skipped")
            continue
        pdir = out / "plugins" / pname
        for s in members:
            _copy_skill(s, pdir / "skills" / s.name)
        _write_json(
            pdir / ".claude-plugin" / "plugin.json",
            {
                "name": pname,
                "version": pdef.version,
                "description": pdef.description,
                "author": {"name": market.owner},
            },
        )
        (pdir / "README.md").write_text(
            _plugin_readme(pname, pdef.description, market.repository, members)
        )
        entries.append(
            {"name": pname, "source": f"./plugins/{pname}", "description": pdef.description}
        )
        result.plugins[pname] = [s.name for s in members]

    _write_json(
        out / ".claude-plugin" / "marketplace.json",
        {
            "name": market.name,
            "owner": {"name": market.owner},
            "metadata": {"description": market.description},
            "plugins": entries,
        },
    )
    return result


def build(root: Path) -> BuildResult:
    """Regenerate plugins/ and .claude-plugin/ in place."""
    with tempfile.TemporaryDirectory() as tmp:
        staging = Path(tmp)
        result = _render(root, staging)
        for sub in ("plugins", ".claude-plugin"):
            target = root / sub
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(staging / sub, target)
    return result


def _diff(a: Path, b: Path, rel: Path = Path()) -> list[str]:
    if not a.exists() or not b.exists():
        return [f"{rel or '.'}: {'missing in repo' if not b.exists() else 'unexpected'}"]
    cmp = filecmp.dircmp(a, b)
    out = [str(rel / n) + ": missing in repo" for n in cmp.left_only]
    out += [str(rel / n) + ": not produced by build" for n in cmp.right_only]
    out += [str(rel / n) + ": differs" for n in cmp.diff_files]
    out += [str(rel / n) + ": not comparable" for n in cmp.funny_files]
    for sub in cmp.common_dirs:
        out += _diff(a / sub, b / sub, rel / sub)
    # dircmp compares shallowly (size+mtime); confirm "same" files byte-for-byte.
    out += [
        str(rel / n) + ": differs"
        for n in cmp.same_files
        if (a / n).read_bytes() != (b / n).read_bytes()
    ]
    return out


def check(root: Path) -> list[str]:
    """Return differences between a fresh build and the committed generated files."""
    with tempfile.TemporaryDirectory() as tmp:
        staging = Path(tmp)
        _render(root, staging)
        problems: list[str] = []
        for sub in ("plugins", ".claude-plugin"):
            problems += _diff(staging / sub, root / sub, Path(sub))
        return problems
